import { expect } from '@playwright/test'
import { join } from 'node:path'

export async function verifyPlayerControls(app, page, output) {
  const player = page.locator('.media-player')
  const video = page.locator('.media-video')
  const heading = page.locator('.media-player-heading')
  const controls = page.locator('.media-player-controls')
  const opacity = (locator) =>
    locator.evaluate((element) => Number(getComputedStyle(element).opacity))
  const run = (name) => page.getByRole('button', { name, exact: true }).click()
  await expect.poll(() => video.evaluate((element) => element.muted)).toBe(true)
  await run('取消静音')
  await expect.poll(() => video.evaluate((element) => element.muted)).toBe(false)
  const center = async () => {
    const box = await player.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  }
  await expect(player).toHaveAttribute('data-intro', 'true')
  await expect.poll(() => opacity(controls)).toBe(1)
  await expect.poll(() => opacity(heading)).toBe(1)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await center()
  await expect(player).toHaveAttribute('data-intro', 'false', { timeout: 4000 })
  await expect.poll(() => opacity(controls)).toBe(0)
  await expect.poll(() => opacity(heading)).toBe(0)
  expect(await video.evaluate((element) => element.controls)).toBe(false)
  // 画面中部移动不会唤醒任一控制区。
  const box = await player.boundingBox()
  await page.mouse.move(box.x + box.width / 3, box.y + box.height / 3, { steps: 5 })
  expect(await opacity(controls)).toBe(0)
  expect(await opacity(heading)).toBe(0)
  await page.screenshot({ path: join(output, '播放器-自动隐藏.png'), scale: 'css' })

  await controls.hover()
  await expect.poll(() => opacity(controls)).toBe(1)
  expect(await opacity(heading)).toBe(0)
  await run('暂停播放')
  await center()
  await expect.poll(() => opacity(controls)).toBe(0)
  expect(await video.evaluate((element) => element.paused)).toBe(true)
  await heading.hover()
  await expect.poll(() => opacity(heading)).toBe(1)
  expect(await opacity(controls)).toBe(0)
  await center()
  await expect.poll(() => opacity(heading)).toBe(0)

  // 隐藏后键盘仍可逐项操作，鼠标点击不会留下常驻焦点控件。
  await player.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '返回详情', exact: true })).toBeFocused()
  await expect.poll(() => opacity(heading)).toBe(1)
  await page.keyboard.press('Tab')
  const timeline = page.getByRole('slider', { name: '播放进度' })
  await expect(timeline).toBeFocused()
  await expect.poll(() => opacity(controls)).toBe(1)
  await page.keyboard.press('Home')
  await expect.poll(() => video.evaluate((element) => element.currentTime)).toBe(0)
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => video.evaluate((element) => element.currentTime)).toBe(15)

  // 首次点击后进度条须保持在目标位置，不能在视频完成定位前回跳到旧时间。
  await timeline.evaluate((element) => {
    element.addEventListener('click', () => (element.dataset.clickValue = element.value), {
      once: true,
    })
  })
  const firstTrack = await timeline.boundingBox()
  await page.mouse.click(firstTrack.x + firstTrack.width / 3, firstTrack.y + firstTrack.height / 2)
  const firstClickValue = Number(await timeline.getAttribute('data-click-value'))
  expect(firstClickValue).toBeGreaterThanOrEqual(28)
  expect(firstClickValue).toBeLessThanOrEqual(32)
  await expect
    .poll(async () => Math.round(await video.evaluate((element) => element.currentTime)))
    .toBe(30)

  const track = await timeline.boundingBox()
  await page.mouse.move(track.x + 6, track.y + track.height / 2)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width / 2, track.y - 80, { steps: 4 })
  await expect.poll(() => opacity(controls)).toBe(1)
  await page.mouse.up()
  await expect.poll(() => video.evaluate((element) => Math.round(element.currentTime))).toBe(45)
  await center()
  await expect.poll(() => opacity(controls)).toBe(0)
  await run('静音')
  await expect.poll(() => video.evaluate((element) => element.muted)).toBe(true)
  await run('取消静音')
  await expect.poll(() => video.evaluate((element) => element.muted)).toBe(false)
  const volume = page.getByRole('slider', { name: '音量' })
  await volume.focus()
  await page.keyboard.press('End')
  await page.keyboard.press('ArrowDown')
  await expect.poll(() => video.evaluate((element) => element.volume)).toBe(0.95)
  await player.focus()

  const subtitlePicker = page.getByRole('button', { name: '选择字幕', exact: true })
  const subtitleMenu = page.getByRole('listbox', { name: '字幕轨道' })
  await subtitlePicker.focus()
  await page.keyboard.press('ArrowDown')
  await expect(subtitleMenu.getByRole('option', { selected: true })).toBeFocused()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(subtitlePicker).toContainText('字幕关闭')
  await expect(page.locator('.media-player-subtitles')).toHaveCount(0)
  await subtitlePicker.press('ArrowUp')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(subtitlePicker).toContainText('中文简体')
  await expect(video).toBeVisible()

  // 选择字幕后焦点留在按钮上，左右键仍应分别跳转 15 秒。
  await expect(subtitlePicker).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => video.evaluate((element) => Math.round(element.currentTime))).toBe(60)
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => video.evaluate((element) => Math.round(element.currentTime))).toBe(45)
  // 音量滑块使用上下键调节音量，左右键继续控制播放进度。
  await volume.focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => video.evaluate((element) => Math.round(element.currentTime))).toBe(30)
  await expect.poll(() => video.evaluate((element) => element.volume)).toBe(0.95)
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => video.evaluate((element) => Math.round(element.currentTime))).toBe(45)

  for (const theme of ['初号机主题', '深色模式', '浅色模式', '钢铁侠主题']) {
    await run(theme)
    await controls.hover()
    await expect.poll(() => opacity(controls)).toBe(1)
    await page.screenshot({ path: join(output, `播放器-控制栏-${theme}.png`), scale: 'css' })
    await timeline.focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowLeft')
    await expect.poll(() => opacity(controls)).toBe(1)
    await page.screenshot({ path: join(output, `播放器-进度焦点-${theme}.png`), scale: 'css' })
    await subtitlePicker.click()
    await expect(subtitleMenu).toBeVisible()
    await expect.poll(() => opacity(controls)).toBe(1)
    await page.screenshot({ path: join(output, `播放器-字幕菜单-${theme}.png`), scale: 'css' })
    await page.keyboard.press('Escape')
    await expect(subtitleMenu).toHaveCount(0)
    await expect(subtitlePicker).toBeFocused()
    await expect(video).toBeVisible()
  }
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1060, 760))
  await controls.hover()
  await expect(page.getByRole('button', { name: '全屏', exact: true })).toBeInViewport()
  await page.screenshot({ path: join(output, '播放器-控制栏-最小窗口.png'), scale: 'css' })
  await subtitlePicker.click()
  const menuBounds = await subtitleMenu.boundingBox()
  const playerBounds = await player.boundingBox()
  expect(menuBounds.x).toBeGreaterThanOrEqual(playerBounds.x)
  expect(menuBounds.x + menuBounds.width).toBeLessThanOrEqual(playerBounds.x + playerBounds.width)
  expect(
    await subtitleMenu.evaluate((element) => element.scrollWidth - element.clientWidth),
  ).toBeLessThanOrEqual(1)
  await page.screenshot({ path: join(output, '播放器-字幕菜单-最小窗口.png'), scale: 'css' })
  await page.keyboard.press('Escape')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].maximize())
  await controls.hover()
  await page.screenshot({ path: join(output, '播放器-控制栏-最大化.png'), scale: 'css' })
  await app.evaluate(({ BrowserWindow }) => {
    const window = BrowserWindow.getAllWindows()[0]
    window.unmaximize()
    window.setSize(1480, 900)
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await controls.hover()
  expect(await controls.evaluate((element) => getComputedStyle(element).transitionDuration)).toBe(
    '0s',
  )
  await player.focus()
  await center()
  await page.keyboard.press('Space')
  await expect.poll(() => video.evaluate((element) => element.paused)).toBe(false)
  expect(await opacity(controls)).toBe(0)
}
